import { useQuery } from '@tanstack/react-query'

import { getSummary } from '../api/notes'
import type { PatientSummary } from '../api/types'
import { actionItemTiming, summaryCoverage } from '../format'
import { ErrorMessage } from './ErrorMessage'

const FALLBACK_REASONS: Record<NonNullable<PatientSummary['fallback_reason']>, string> = {
  not_configured: 'Generated summaries aren’t set up on this server.',
  provider_error: 'The summary service couldn’t produce a summary.',
}

/**
 * The patient summary, labeled so nobody mistakes it for a full chart review.
 *
 * Everything about the summary (what it covers, where it came from) sits in one box at the top,
 * so the summary below reads without interruption. The API's headline (age, allergies, conditions)
 * isn't shown: the chart header, allergy banner and profile card already show those facts.
 * The narrative is generated from the notes when the server can, and otherwise is the built-in
 * timeline, labeled as such. The full notes stay on the same page, one link away.
 */
export function SummaryPanel({ patientId }: { patientId: string }) {
  const { data, error, isPending, isFetching, refetch } = useQuery({
    queryKey: ['patient', patientId, 'summary'],
    queryFn: () => getSummary(patientId),
  })

  return (
    <section className="card" aria-labelledby="summary-heading" aria-busy={isFetching}>
      <h2 id="summary-heading">Summary</h2>
      {isPending ? (
        <Working>Preparing summary… The first one for new notes can take 10–20 seconds.</Working>
      ) : !data ? (
        <ErrorMessage error={error} onRetry={() => refetch()} />
      ) : (
        <div className="summary-body">
          {/* A failed background refresh keeps the summary being read on screen. */}
          {error && <ErrorMessage error={error} onRetry={() => refetch()} />}
          {/* After a note is added, the old summary stays until the new one is ready. */}
          {isFetching && <Working>Updating summary for the latest notes…</Working>}
          <About summary={data} />
          {data.source === 'llm' && data.notes_shortened > 0 && (
            <p className="source-label source-label-fallback">
              {data.notes_shortened === 1
                ? '1 note was too long to use in full.'
                : `${data.notes_shortened} notes were too long to use in full.`}{' '}
              Only the beginning of each was used, so its later sections, often the assessment and
              plan, may be missing here.
            </p>
          )}
          {data.source === 'llm' ? <Generated summary={data} /> : <BuiltIn summary={data} />}
          {data.notes_total > 0 && (
            <p className="muted small">
              <a href="#notes-heading">Read the full notes</a>
            </p>
          )}
        </div>
      )}
    </section>
  )
}

/** What the summary covers and where it came from. */
function About({ summary }: { summary: PatientSummary }) {
  const { scope, span } = summaryCoverage(summary)
  const source =
    summary.source === 'llm'
      ? 'The summary and action items below are generated by a language model from the notes. ' +
        'They can be wrong or leave things out, so check them against the notes.'
      : summary.fallback_reason
        ? `Built-in summary. ${FALLBACK_REASONS[summary.fallback_reason]}`
        : null
  return (
    <div className="summary-about">
      <p className="summary-scope">{scope}</p>
      {span && <p>{span}</p>}
      {source && <p className="summary-source">{source}</p>}
    </div>
  )
}

function Generated({ summary }: { summary: PatientSummary }) {
  return (
    <>
      {summary.narrative.split(/\n+/).map((paragraph, index) => (
        <p key={index}>{paragraph}</p>
      ))}
      <h3 className="action-items-heading">Action items from the notes</h3>
      {summary.action_items.length > 0 ? (
        <ul className="action-items">
          {summary.action_items.map((item, index) => (
            <li key={index}>
              <span className="action-item-name">{item.action}</span>
              {item.overdue && <span className="overdue">Overdue</span>}
              <span className="action-item-timing">{actionItemTiming(item)}</span>
            </li>
          ))}
        </ul>
      ) : (
        <p className="muted">None found in these notes.</p>
      )}
    </>
  )
}

/**
 * A spinner with a message. There's no progress bar because the server can't report how far
 * along a summary is; a bar would only be a guess.
 */
function Working({ children }: { children: string }) {
  return (
    <p className="working muted" role="status">
      <span className="spinner" aria-hidden="true" />
      {children}
    </p>
  )
}

function BuiltIn({ summary }: { summary: PatientSummary }) {
  return (
    <>
      {/* The API puts each note on its own line. */}
      <ul className="timeline">
        {summary.narrative.split('\n').map((line, index) => (
          <li key={index}>{line}</li>
        ))}
      </ul>
      {summary.notes_total > 0 && (
        <p className="muted small">
          Each line is the note’s assessment and plan, or the opening of notes not written in SOAP
          format, so other details may be missing.
        </p>
      )}
    </>
  )
}
