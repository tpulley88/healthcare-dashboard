import type { Page } from '@playwright/test'

import { createPatient, deletePatient, expect, test } from './helpers'

/**
 * Answer the summary request without calling the real model:
 * take the server's built-in summary and change it as the server would.
 */
async function answerSummary(page: Page, changes: Record<string, unknown>) {
  await page.route('**/api/patients/*/summary', async (route) => {
    const url = new URL(route.request().url())
    url.searchParams.set('source', 'template')
    const builtIn = await route.fetch({ url: url.toString() })
    await route.fulfill({ json: { ...(await builtIn.json()), ...changes } })
  })
}

test.describe('patient summary', () => {
  let patientId: string

  test.beforeEach(async ({ request }) => {
    patientId = (await createPatient(request)).id
    for (const [taken_at, content] of [
      [
        '2026-03-01T09:00:00-05:00',
        'S: Headaches.\nO: BP 148/92.\nA: Hypertension, above goal.\nP: Start lisinopril 10 mg.',
      ],
      ['2026-09-20T09:30:00-04:00', 'Telephone follow-up. Home BP readings now 126/80.'],
    ]) {
      const response = await request.post(`/api/patients/${patientId}/notes`, {
        data: { taken_at, content },
      })
      expect(response.status()).toBe(201)
    }
  })

  test.afterEach(async ({ request }) => {
    await deletePatient(request, patientId)
  })

  test('a generated narrative is labeled as model-written', async ({ page }) => {
    await answerSummary(page, {
      source: 'llm',
      narrative: 'Started lisinopril in March.\nHome readings improved by September.',
      action_items: [
        { action: 'Repeat BMP', noted_on: '2026-03-01', due_on: '2026-09-01', overdue: true },
        { action: 'Screening labs', noted_on: '2026-09-20', due_on: null, overdue: false },
      ],
    })
    await page.goto(`/patients/${patientId}`)

    const summary = page.getByRole('region', { name: 'Summary' })
    await expect(summary).toContainText('Home readings improved by September.')
    // What the summary covers and where it came from come first, then the summary itself.
    const text = await summary.innerText()
    const order = [
      'Not a complete clinical history · Summary of 2 notes',
      'Mar 1, 2026 – Sep 20, 2026',
      'generated by a language model',
      'Started lisinopril in March.',
      'Action items from the notes',
    ].map((part) => text.indexOf(part))
    expect(order).not.toContain(-1)
    expect(order).toEqual([...order].sort((a, b) => a - b))
    // Age, allergies and conditions are already in the chart header and profile card.
    await expect(summary).not.toContainText('year-old')
    await expect(
      summary.getByRole('heading', { name: 'Action items from the notes' }),
    ).toBeVisible()
    // Each item says when it's due (or that no date was given) and which note it came from.
    const items = summary.getByRole('listitem')
    await expect(items).toHaveCount(2)
    await expect(items.nth(0)).toContainText('Repeat BMP')
    await expect(items.nth(0)).toContainText('Due Sep 1, 2026 · from the Mar 1, 2026 note')
    await expect(items.nth(0).getByText('Overdue', { exact: true })).toBeVisible()
    await expect(items.nth(1)).toContainText('No due date given · from the Sep 20, 2026 note')
    await expect(items.nth(1)).not.toContainText('Overdue')
    await expect(summary).not.toContainText('Built-in summary')
    await expect(summary).not.toContainText('too long to use in full')
  })

  test('a generated narrative says when a note was too long to use in full', async ({ page }) => {
    await answerSummary(page, {
      source: 'llm',
      narrative: 'Palpitations reported in September.',
      notes_shortened: 1,
    })
    await page.goto(`/patients/${patientId}`)

    const summary = page.getByRole('region', { name: 'Summary' })
    await expect(summary).toContainText('1 note was too long to use in full.')
    await expect(summary).toContainText('None found in these notes.')
    await expect(summary).toContainText('often the assessment and plan, may be missing here')
  })

  test('the built-in summary uses assessment and plan, and says why it is shown', async ({
    page,
  }) => {
    await answerSummary(page, { fallback_reason: 'provider_error' })
    await page.goto(`/patients/${patientId}`)

    const summary = page.getByRole('region', { name: 'Summary' })
    await expect(summary).toContainText(
      'Built-in summary. The summary service couldn’t produce a summary.',
    )
    // Newest first, like the notes list.
    await expect(summary.getByRole('listitem')).toHaveText([
      /^Sep 20, 2026 \(most recent, 6 months after the previous note\): Telephone follow-up\./,
      'Mar 1, 2026: Hypertension, above goal. Plan: Start lisinopril 10 mg.',
    ])
    // A note that isn't in SOAP format contributes its opening instead.
    await expect(summary).toContainText('Telephone follow-up.')
    await expect(summary).not.toContainText('Headaches')
  })

  test('a spinner shows while the summary is prepared, and while it updates for a new note', async ({
    page,
  }) => {
    // Hold each summary response until the test lets it through.
    let release: () => void = () => {}
    await page.route('**/api/patients/*/summary', async (route) => {
      await new Promise<void>((resolve) => (release = resolve))
      await route.fallback()
    })
    await page.goto(`/patients/${patientId}`)
    const summary = page.getByRole('region', { name: 'Summary' })

    await expect(summary.getByRole('status')).toContainText('Preparing summary…')
    await expect(summary.locator('.spinner')).toBeVisible()
    release()
    await expect(summary).toContainText('Telephone follow-up.')
    await expect(summary.getByRole('status')).toHaveCount(0)

    await page.getByRole('textbox', { name: 'Note' }).fill('Phone check-in. Doing well.')
    await page.getByRole('button', { name: 'Add note' }).click()
    // The previous summary stays readable while the new one is prepared.
    await expect(summary.getByRole('status')).toContainText(
      'Updating summary for the latest notes…',
    )
    await expect(summary).toContainText('Telephone follow-up.')
    release()
    await expect(summary).toContainText('Phone check-in.')
    await expect(summary.getByRole('status')).toHaveCount(0)
  })
})
